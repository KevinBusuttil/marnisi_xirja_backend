"""Actual Dart-generated checkout examples must also validate on Python 3.14.

Fixture is generated by the Marnisi frontend tool/build_fiscal_contract_fixture.dart;
it includes all requested catalogue prices, quantity/discount combinations and exact
cross-language payload hashes. Keep the backend copy for standalone reproducibility.
"""
import json
import os
from pathlib import Path
import pytest
from xirja_marnisi.fiscal.core import digest, money, number
from xirja_marnisi.fiscal.validation import validate_sale

FIXTURE = Path(__file__).parent / 'fixtures' / 'marnisi_fiscal_contract.json'
EXAMPLES = json.loads(FIXTURE.read_text())


@pytest.mark.parametrize('example', EXAMPLES, ids=lambda row:row['payload']['sales_num'])
def test_actual_flutter_checkout_validates_and_has_identical_frozen_hash(example):
    payload=example['payload']
    assert validate_sale(payload)['total'] == money(payload['fiscal_final_total'])
    assert digest(payload) == example['payload_hash']
    line=payload['items'][0]
    assert money(number(line['si_price']) * (1 + number(line['si_tax_pct']) / 100)) == money(number(example['catalogue_net']) * (1 + number(line['si_tax_pct']) / 100))


def test_frontend_fixture_has_not_drifted_when_both_repositories_available():
    sibling = Path(os.environ.get('MARNISI_FRONTEND_PATH', Path(__file__).resolve().parents[4] / 'XIRJA-frontend-marnisi'))
    frontend_fixture=sibling/'test'/'fixtures'/'marnisi_fiscal_contract.json'
    if frontend_fixture.exists():
        assert json.loads(frontend_fixture.read_text()) == EXAMPLES
